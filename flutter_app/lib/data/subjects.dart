/// The section [k] belongs to.
Subject? subjectOf(AyahKey k) {
  final code = k.sura * 1000 + k.ayah;
  // The last start at or before the ayah.
  var lo = 0, hi = _starts.length - 1;
  if (code < _starts.first) return null;
  while (lo < hi) {
    final mid = (lo + hi + 1) ~/ 2;
    if (_starts[mid] <= code) {
      lo = mid;
    } else {
      hi = mid - 1;
    }
  }
  final start = _starts[lo], end = _ends[lo];
  return Subject(lo, AyahKey(start ~/ 1000, start % 1000), AyahKey(end ~/ 1000, end % 1000));
}

/// How many sections there are.
int get subjectCount => _starts.length;
