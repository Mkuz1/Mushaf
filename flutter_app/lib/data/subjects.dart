/// A passage on one subject or story: one of the Quran's 556 ruku' sections (the classical thematic
/// divisions printed in many mushafs), coloured on the page when subjects are shown.
class Subject {
  /// 0 to 555, in the order of the Quran.
  final int index;
  final AyahKey from, to;
  const Subject(this.index, this.from, this.to);

  /// Neighbouring sections never share a colour (nor do any six in a row).
  Color get color => subjectColors[index % subjectColors.length];

  bool contains(AyahKey k) => from.compareTo(k) <= 0 && k.compareTo(to) <= 0;

  @override
  bool operator ==(Object other) => other is Subject && other.index == index;

  @override
  int get hashCode => index;
}

